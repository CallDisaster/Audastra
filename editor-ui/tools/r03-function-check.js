async (page) => {
  const checks=[];
  const assert=(ok,label)=>{if(!ok)throw new Error(label);checks.push(label);};
  await page.getByRole('button',{name:'打开工程',exact:true}).click();
  await page.getByRole('button',{name:'打开示例工程',exact:true}).click();
  await page.getByRole('button',{name:'触发器模块',exact:true}).click();
  await page.getByRole('button',{name:'蓝图',exact:true}).click();
  await page.getByRole('button',{name:'适应画布 · F',exact:true}).click();
  const spawn=page.locator('.tw-node[data-definition="core.spawn"]');
  const open=()=>spawn.getByRole('button',{name:'对象模板参数来源',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'对象模板选择器',exact:true});
  await open();
  assert((await panel.getByRole('tab').allTextContents()).join('|')==='全局变量|函数|固定值','三种来源按全局变量、函数、固定值排列');
  await panel.getByRole('tab',{name:'全局变量',exact:true}).click();
  assert(await panel.getByRole('button',{name:'选择变量 playerHero',exact:true}).count()===0,'单位类型参数不混入单位实例变量');
  await panel.getByRole('button',{name:'选择变量 spawnUnitType',exact:true}).click();
  assert((await spawn.getByRole('button',{name:'选择对象模板',exact:true}).textContent()).includes('spawnUnitType'),'单位类型可直接选择全局变量');
  await open();
  await panel.getByRole('tab',{name:'函数',exact:true}).click();
  assert(await panel.getByRole('button',{name:'选择函数 触发单位',exact:true}).count()===0,'单位类型函数列表排除单位实例返回值');
  await panel.getByRole('textbox',{name:'搜索函数',exact:true}).fill('GetUnitTypeId');
  await panel.getByRole('button',{name:'选择函数 单位的单位类型',exact:true}).click();
  await panel.getByRole('button',{name:'选择函数参数 单位',exact:true}).click();
  await panel.getByRole('tab',{name:'函数',exact:true}).click();
  await panel.getByRole('button',{name:'选择函数 触发单位',exact:true}).click();
  assert((await panel.getByRole('button',{name:'选择函数参数 单位',exact:true}).textContent()).includes('触发单位'),'函数入参支持嵌套函数选择');
  await panel.getByRole('button',{name:'应用函数',exact:true}).click();
  await panel.waitFor({state:'hidden'});
  await page.getByRole('button',{name:'代码',exact:true}).click();
  for(const language of ['JASS','vJass','Lua']) {
    await page.getByRole('combobox',{name:'代码语言',exact:true}).selectOption(language);
    assert((await page.getByRole('textbox',{name:'触发器代码',exact:true}).inputValue()).includes('GetUnitTypeId(GetTriggerUnit())'),`${language}预览保留嵌套取值语义`);
  }
  await page.getByRole('button',{name:'蓝图',exact:true}).click();
  await open();
  await panel.getByRole('button',{name:'选择函数参数 单位',exact:true}).click();
  await panel.getByRole('tab',{name:'全局变量',exact:true}).click();
  await panel.getByRole('button',{name:'选择变量 playerHero',exact:true}).click();
  const index=panel.getByRole('textbox',{name:'数组下标',exact:true});
  await index.fill('3'); await index.press('Enter');
  await panel.getByRole('button',{name:'应用函数',exact:true}).click();
  await page.getByRole('button',{name:'代码',exact:true}).click();
  await page.getByRole('combobox',{name:'代码语言',exact:true}).selectOption('JASS');
  assert((await page.getByRole('textbox',{name:'触发器代码',exact:true}).inputValue()).includes('GetUnitTypeId(udg_playerHero[3])'),'函数入参支持全局数组并生成对应下标');
  await page.getByRole('button',{name:'保存工程',exact:true}).click();
  await page.reload({waitUntil:'domcontentloaded'});
  await open();
  assert((await panel.getByRole('button',{name:'选择函数参数 单位',exact:true}).textContent()).includes('playerHero[3]'),'保存重新打开保留函数与数组参数结构');
  await panel.getByRole('tab',{name:'固定值',exact:true}).click();
  await panel.getByRole('textbox',{name:'搜索物体名称或 rawcode',exact:true}).fill('h003');
  const mage=panel.getByRole('button',{name:'选择奥术法师 h003',exact:true});
  await mage.hover();
  await panel.getByRole('tooltip',{name:'奥术法师详细信息',exact:true}).waitFor({state:'visible'});
  assert(await mage.getByRole('img',{name:'奥术法师',exact:true}).count()===1,'候选头像可见且悬停显示对象详情');
  await mage.click();
  assert((await spawn.getByRole('button',{name:'选择对象模板',exact:true}).textContent()).includes('奥术法师'),'函数来源可切回固定物体值');
  await page.getByRole('button',{name:'代码',exact:true}).click();
  const code=await page.getByRole('textbox',{name:'触发器代码',exact:true}).inputValue();
  assert(code.includes("'h003'") && !code.includes('GetUnitTypeId(udg_playerHero[3])'),'切回固定值实际移除旧函数绑定');
  await page.getByRole('button',{name:'蓝图',exact:true}).click();
  await page.getByRole('button',{name:'保存工程',exact:true}).click();
  return {passed:checks.length,checks};
}
