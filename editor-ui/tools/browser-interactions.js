async (page) => {
    const passed = [];
    const assert = (ok, message) => { if (!ok) throw new Error(message); passed.push(message); };
    await page.getByRole('button', { name: '打开工程', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: '通用工程示例', exact: true }).click();
    await page.getByRole('button', { name: '保存', exact: true }).click();
    const node = page.locator('[data-node="node-2"] .node-title');
    const box = await node.boundingBox();
    await page.mouse.move(box.x + 30, box.y + 15); await page.mouse.down();
    await page.mouse.move(box.x + 90, box.y + 47, { steps: 10 }); await page.mouse.up();
    await page.getByRole('button', { name: '文档', exact: true }).click();
    let graph = JSON.parse(await page.getByRole('textbox', { name: '蓝图 JSON 文档', exact: true }).inputValue());
    assert(graph.nodes.find(n => n.id === 'node-2').x > 700, '拖动节点写入工程坐标');
    await page.getByRole('button', { name: '撤销', exact: true }).click();
    await page.locator('.segmented').getByRole('button', { name: '蓝图', exact: true }).click();
    await page.getByRole('button', { name: '定时事件 触发 输出', exact: true }).click();
    await page.getByRole('button', { name: '输出消息 执行 输入', exact: true }).click();
    await page.getByRole('button', { name: '文档', exact: true }).click();
    graph = JSON.parse(await page.getByRole('textbox', { name: '蓝图 JSON 文档', exact: true }).inputValue());
    assert(graph.edges.find(e => e.to === 'node-5').from === 'node-0', '有效连线替换同一输入');
    await page.getByRole('button', { name: '撤销', exact: true }).click();
    await page.locator('.segmented').getByRole('button', { name: '蓝图', exact: true }).click();
    await page.getByRole('button', { name: '创建对象', exact: true }).click();
    await page.getByRole('button', { name: '删除', exact: true }).click();
    await page.getByRole('button', { name: '文档', exact: true }).click();
    graph = JSON.parse(await page.getByRole('textbox', { name: '蓝图 JSON 文档', exact: true }).inputValue());
    assert(graph.nodes.length === 5 && graph.edges.every(e => e.to !== 'node-2' && e.from !== 'node-2'), '删除节点同步清理连线');
    await page.getByRole('button', { name: '撤销', exact: true }).click();
    await page.locator('.segmented').getByRole('button', { name: '蓝图', exact: true }).click();
    assert(await page.locator('.graph-node').count() === 6, '撤销恢复节点与连线');
    await page.getByRole('button', { name: '创建对象', exact: true }).click();
    for (const [width, height] of [[1440, 900], [1024, 768], [760, 800], [390, 844]]) {
        await page.setViewportSize({ width, height });
        const layout = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth, canvas: document.querySelector('.blueprint').getBoundingClientRect().width }));
        assert(layout.scroll <= width && layout.canvas > 300, `${width}x${height} 无水平溢出且保留画布`);
    }
    await page.getByRole('button', { name: '切换属性面板', exact: true }).click();
    assert(await page.getByRole('spinbutton', { name: '数量', exact: true }).isVisible(), '窄屏属性面板可打开');
    await page.getByRole('button', { name: '切换属性面板', exact: true }).click();
    await page.getByRole('button', { name: '切换工程树', exact: true }).click();
    assert(await page.getByRole('button', { name: '工程初始化', exact: true }).isVisible(), '窄屏工程树可打开');
    await page.getByRole('button', { name: '切换工程树', exact: true }).click();
    await page.setViewportSize({ width: 1600, height: 1000 });
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('combobox', { name: '界面主题', exact: true }).selectOption('paper');
    await page.getByRole('button', { name: '关闭对话框', exact: true }).click();
    assert(await page.locator('.theme-paper').count() === 1, '浅色主题可切换');
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('combobox', { name: '界面主题', exact: true }).selectOption('graphite');
    await page.getByRole('button', { name: '关闭对话框', exact: true }).click();
    await page.getByRole('button', { name: '保存', exact: true }).click();
    return { passed: passed.length, checks: passed };
}
