// Run with the project's browser test runner against a dedicated test page.
// This script loads the sample through the UI; it neither opens a browser nor reads app storage.
async (page) => {
  const checks = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); checks.push(message); };
  const node = definition => page.locator(`.tw-node[data-definition="${definition}"]`);
  const picker = label => page.getByRole('dialog', { name: `${label}选择器`, exact: true });
  const source = (definition, label) => node(definition).getByRole('button', { name: `${label}参数来源`, exact: true });
  const undo = () => page.getByRole('button', { name: '撤销', exact: true }).click();
  const geometry = async () => page.locator('.tw-node[data-node-id]').evaluateAll(elements => elements.map(element => {
    const rect = element.getBoundingClientRect();
    return { id: element.getAttribute('data-node-id'), x: Math.round(rect.x * 100) / 100, y: Math.round(rect.y * 100) / 100, width: Math.round(rect.width * 100) / 100 };
  }));
  const sameGeometry = (before, after) => JSON.stringify(before) === JSON.stringify(after);
  const zoomLabel = () => page.getByTitle('实际大小 · 100%', { exact: true }).textContent();
  const assertPicker = async (label, anchor, requireBeside = true) => {
    const panel = picker(label);
    await panel.waitFor({ state: 'visible' });
    assert(await panel.getAttribute('aria-modal') !== 'true', `${label}选择器不声明模态`);
    assert(await page.locator('.tw-backdrop:visible,.tw-menu-dismiss:visible').count() === 0, `${label}选择器无遮罩`);
    const panelBox = await panel.boundingBox();
    const anchorBox = await anchor.boundingBox();
    const viewport = page.viewportSize();
    assert(panelBox && panelBox.x >= 0 && panelBox.y >= 0 && panelBox.x + panelBox.width <= viewport.width + 1 && panelBox.y + panelBox.height <= viewport.height + 1, `${label}选择器位于视口内`);
    if (requireBeside) assert(panelBox.x >= anchorBox.x + anchorBox.width - 26 || panelBox.x + panelBox.width <= anchorBox.x + 26, `${label}选择器位于节点旁侧`);
    assert(await panel.evaluate(element => {
      const rect = element.getBoundingClientRect();
      const hit = document.elementFromPoint(rect.left + rect.width / 2, rect.top + Math.min(50, rect.height / 2));
      return !!hit && element.contains(hit);
    }), `${label}选择器处于可交互的顶层`);
    return panel;
  };

  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.getByRole('button', { name: '打开工程', exact: true }).click();
  await page.getByRole('button', { name: '打开示例工程', exact: true }).click();
  await page.getByRole('button', { name: '触发器模块', exact: true }).click();
  await page.getByRole('button', { name: '蓝图', exact: true }).click();
  await node('core.interval').waitFor({ state: 'visible' });
  await page.getByRole('button', { name: '适应画布 · F', exact: true }).click();
  const originalGeometry = await geometry();
  const originalNodeCount = await page.locator('.tw-node[data-node-id]').count();
  const interval = node('core.interval').getByRole('textbox', { name: '间隔 / 秒', exact: true });
  const originalInterval = await interval.inputValue();

  await interval.fill('47');
  await interval.press('Enter');
  assert(await interval.inputValue() === '47', '数字参数直接 Enter 提交');
  assert(await page.locator('.tw-backdrop:visible').count() === 0, '数字参数不打开模态窗口');
  assert(sameGeometry(originalGeometry, await geometry()), '数字输入不移动或缩放节点');
  await interval.fill('99');
  await interval.press('Escape');
  await interval.press('Tab');
  assert(await interval.inputValue() === '47', '数字 Escape 取消且随后失焦不误提交');
  await undo();
  assert(await interval.inputValue() === originalInterval, '一次撤销还原一次数字提交，无 Enter/blur 双重记录');

  const message = node('core.log').getByRole('textbox', { name: '消息', exact: true });
  const originalMessage = await message.inputValue();
  await message.fill('R03 inline 9857');
  await message.press('Enter');
  assert(await message.inputValue() === 'R03 inline 9857', '文本参数直接提交');
  await message.fill('R03 cancelled');
  await message.press('Escape');
  await message.press('Tab');
  assert(await message.inputValue() === 'R03 inline 9857', '文本 Escape 取消草稿');
  await undo();
  assert(await message.inputValue() === originalMessage, '文本参数一次撤销恢复原值');

  const repeat = node('core.interval').getByRole('switch', { name: '循环', exact: true });
  const originalRepeat = await repeat.getAttribute('aria-checked');
  await repeat.click();
  assert(await repeat.getAttribute('aria-checked') !== originalRepeat, '布尔参数行内切换');
  await undo();
  assert(await repeat.getAttribute('aria-checked') === originalRepeat, '布尔参数一次撤销恢复');

  await interval.click();
  const selectedCount = await page.locator('.tw-node.selected').count();
  await interval.press('Control+a');
  assert(await page.locator('.tw-node.selected').count() === selectedCount, '输入框 Ctrl+A 不触发图节点全选');
  await interval.press('Backspace');
  assert(await page.locator('.tw-node[data-node-id]').count() === originalNodeCount, '输入框 Backspace 不删除节点');
  await interval.press('Control+z');
  await interval.press('Escape');
  await interval.press('Tab');
  assert(await interval.inputValue() === originalInterval && await page.locator('.tw-node[data-node-id]').count() === originalNodeCount, '输入内撤销与 Escape 保持图结构');
  await message.click({ button: 'right' });
  assert(await page.getByRole('textbox', { name: '搜索函数', exact: true }).count() === 0, '参数右键不误开新建节点菜单');
  await message.press('Escape');
  await message.dblclick();
  assert(await page.getByRole('textbox', { name: '搜索函数', exact: true }).count() === 0, '参数双击不新建节点');
  assert(sameGeometry(originalGeometry, await geometry()), '数字、文本、布尔与快捷键操作均不拖动画布');

  const objectAnchor = node('core.spawn').getByRole('button', { name: '选择对象模板', exact: true });
  await objectAnchor.click();
  let objectPanel = await assertPicker('对象模板', objectAnchor);
  const beforePickerGeometry = await geometry();
  const beforePickerZoom = await zoomLabel();
  const panelBox = await objectPanel.boundingBox();
  await page.mouse.move(panelBox.x + panelBox.width / 2, panelBox.y + panelBox.height / 2);
  await page.mouse.wheel(0, 240);
  assert(await zoomLabel() === beforePickerZoom && sameGeometry(beforePickerGeometry, await geometry()), '选择器列表滚轮不缩放或平移蓝图');
  const search = objectPanel.getByRole('textbox', { name: '搜索物体名称或 rawcode', exact: true });
  await search.fill('巡林');
  const archer = objectPanel.getByRole('button', { name: '选择巡林射手 e001', exact: true });
  await archer.waitFor({ state: 'visible' });
  assert(await objectPanel.getByRole('button', { name: '选择守卫步兵 h001', exact: true }).count() === 0, '对象搜索即时筛选列表');
  assert(await archer.locator('img,[role=img],[data-object-avatar],.np-avatar,.np-object-avatar').count() > 0, '对象候选有可见头像入口');
  await archer.click();
  await picker('对象模板').waitFor({ state: 'hidden' });
  assert((await objectAnchor.textContent()).includes('巡林射手'), '点击对象头像所在候选立即提交并关闭选择器');
  assert(sameGeometry(beforePickerGeometry, await geometry()), '对象选择不移动节点');

  await objectAnchor.click();
  objectPanel = await assertPicker('对象模板', objectAnchor);
  await page.getByRole('button', { name: '适应画布 · F', exact: true }).click();
  await picker('对象模板').waitFor({ state: 'hidden' });
  assert(true, '外部点击关闭选择器且画布工具可直接接收点击');

  await source('core.interval', '间隔 / 秒').click();
  const valuePanel = picker('间隔 / 秒');
  await valuePanel.getByRole('tab', { name: '全局变量', exact: true }).click();
  await valuePanel.getByRole('button', { name: '选择变量 spawnCount', exact: true }).click();
  await valuePanel.waitFor({ state: 'hidden' });
  const boundValue = node('core.interval').getByRole('button', { name: '选择间隔 / 秒', exact: true });
  assert((await boundValue.textContent()).includes('spawnCount'), '变量来源绑定直接显示在节点参数');
  await source('core.interval', '间隔 / 秒').click();
  assert(await valuePanel.getByRole('tab', { name: '全局变量', exact: true }).getAttribute('aria-selected') === 'true', '重新打开保留变量来源');
  await valuePanel.getByRole('tab', { name: '函数', exact: true }).click();
  await valuePanel.getByRole('button', { name: '自定义表达式', exact: true }).click();
  const expression = valuePanel.getByRole('textbox', { name: '自定义表达式', exact: true });
  await expression.fill('spawnCount * 2');
  await expression.press('Enter');
  await valuePanel.waitFor({ state: 'hidden' });
  assert((await boundValue.textContent()).includes('spawnCount * 2'), '自定义表达式 Enter 提交为表达式来源');
  await source('core.interval', '间隔 / 秒').click();
  assert(await valuePanel.getByRole('tab', { name: '函数', exact: true }).getAttribute('aria-selected') === 'true', '重新打开保留自定义来源');
  assert(await expression.inputValue() === 'spawnCount * 2', '重新打开保留表达式原文');
  await expression.fill('spawnCount * 99');
  await expression.press('Escape');
  await valuePanel.waitFor({ state: 'hidden' });
  assert((await boundValue.textContent()).includes('spawnCount * 2'), '表达式 Escape 不提交临时修改');
  await undo();
  assert((await boundValue.textContent()).includes('spawnCount'), '撤销表达式恢复原变量绑定');
  await undo();
  assert(await interval.inputValue() === originalInterval, '撤销变量绑定恢复常量输入');

  await objectAnchor.click();
  await picker('对象模板').waitFor({ state: 'visible' });
  await page.setViewportSize({ width: 1024, height: 768 });
  await page.waitForFunction(() => {
    const panel = document.querySelector('.np-popover');
    if (!panel) return false;
    const rect = panel.getBoundingClientRect();
    return rect.left >= 0 && rect.top >= 0 && rect.right <= innerWidth + 1 && rect.bottom <= innerHeight + 1;
  });
  await assertPicker('对象模板', objectAnchor, false);
  const narrowZoom = await zoomLabel();
  const narrowPanel = await picker('对象模板').boundingBox();
  await page.mouse.move(narrowPanel.x + narrowPanel.width / 2, narrowPanel.y + narrowPanel.height / 2);
  await page.mouse.wheel(0, 250);
  assert(await zoomLabel() === narrowZoom, '窄视口选择器滚轮不缩放蓝图');
  await picker('对象模板').getByRole('textbox', { name: '搜索物体名称或 rawcode', exact: true }).press('Escape');
  await picker('对象模板').waitFor({ state: 'hidden' });
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.getByRole('button', { name: '适应画布 · F', exact: true }).click();

  await interval.fill('53');
  await interval.press('Enter');
  await page.getByRole('button', { name: '保存工程', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: '触发器模块', exact: true }).click();
  await page.getByRole('button', { name: '蓝图', exact: true }).click();
  assert(await interval.inputValue() === '53', '行内参数保存并刷新后保留');
  assert((await objectAnchor.textContent()).includes('巡林射手'), '对象选择保存并刷新后保留');
  assert(await page.locator('.tw-node[data-node-id]').count() === originalNodeCount, '回归操作未意外创建或删除节点');

  await page.getByRole('button', { name: '物体模块', exact: true }).click();
  await page.locator('.ow-object-list').getByRole('button', { name: /守卫步兵/ }).click();
  await page.getByRole('button', { name: '编辑技能列表', exact: true }).click();
  const abilityPanel = page.getByRole('dialog', { name: '技能列表编辑器', exact: true });
  const ordered = abilityPanel.getByRole('listbox', { name: '已选技能列表', exact: true });
  const orderedNames = () => ordered.getByRole('option').allTextContents();
  await abilityPanel.waitFor({ state: 'visible' });
  assert(await abilityPanel.getAttribute('aria-modal') === 'false', '物编技能列表使用非模态属性旁面板');
  assert(await abilityPanel.getByRole('tab', { name: '全局变量', exact: true }).count() === 0 && await abilityPanel.getByRole('tab', { name: '函数', exact: true }).count() === 0, '物编引用只有固定值，不提供运行时变量或函数');
  assert(await ordered.getByRole('option').count() === 1 && (await orderedNames())[0].includes('坚守阵地'), '技能列表正确载入已有顺序');
  const abilitySearch = abilityPanel.getByRole('textbox', { name: '搜索物体名称或 rawcode', exact: true });
  await abilitySearch.fill('奥术');
  const bolt = abilityPanel.getByRole('button', { name: '选择奥术冲击 A001', exact: true });
  await bolt.hover();
  await abilityPanel.getByRole('tooltip', { name: '奥术冲击详细信息', exact: true }).waitFor({ state: 'visible' });
  assert(await abilityPanel.getByRole('button', { name: '选择守卫步兵 h001', exact: true }).count() === 0, '技能候选严格限制为技能类型');
  await bolt.click();
  assert(await ordered.getByRole('option').count() === 2 && (await orderedNames())[1].includes('奥术冲击'), '候选点击立即追加到技能列表末尾');
  assert(await abilityPanel.isVisible(), '多值选择保持编辑面板打开');
  await abilitySearch.fill('圣光');
  await abilityPanel.getByRole('button', { name: '选择圣光治疗 A002', exact: true }).click();
  assert(await ordered.getByRole('option').count() === 3 && (await orderedNames())[2].includes('圣光治疗'), '连续添加保留技能顺序');
  await abilityPanel.getByRole('button', { name: '上移所选技能', exact: true }).click();
  assert((await orderedNames())[1].includes('圣光治疗'), '上移改变技能列表顺序');
  await abilityPanel.getByRole('button', { name: '下移所选技能', exact: true }).click();
  assert((await orderedNames())[2].includes('圣光治疗'), '下移改变技能列表顺序');
  await abilityPanel.getByRole('button', { name: '删除所选技能', exact: true }).click();
  assert(await ordered.getByRole('option').count() === 2, '删除仅移除所选技能');
  await ordered.getByRole('option').filter({ hasText: '奥术冲击' }).click();
  await abilityPanel.getByRole('button', { name: '替换', exact: true }).click();
  await abilityPanel.getByRole('textbox', { name: '搜索物体名称或 rawcode', exact: true }).fill('圣光');
  await abilityPanel.getByRole('button', { name: '选择圣光治疗 A002', exact: true }).click();
  assert(await ordered.getByRole('option').count() === 2 && (await orderedNames())[1].includes('圣光治疗'), '替换保留原位置与列表长度');
  await abilityPanel.getByRole('button', { name: '完成', exact: true }).click();
  assert(await page.getByRole('button', { name: '编辑技能列表 圣光治疗', exact: true }).count() === 1, '已选技能以图标芯片直接显示');
  await undo();
  assert(await page.getByRole('button', { name: '编辑技能列表 奥术冲击', exact: true }).count() === 1, '物编引用修改接入统一撤销');
  await page.getByRole('button', { name: '保存工程', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: '物体模块', exact: true }).click();
  await page.locator('.ow-object-list').getByRole('button', { name: /守卫步兵/ }).click();
  await page.getByRole('button', { name: '编辑技能列表', exact: true }).click();
  assert(await ordered.getByRole('option').count() === 2 && (await orderedNames())[1].includes('奥术冲击'), '有序技能列表保存刷新后保留');
  await abilityPanel.getByRole('button', { name: '完成', exact: true }).click();
  return { passed: checks.length, checks };
}
