async (page) => {
  const checks = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); checks.push(message); };
  await page.getByRole('button', { name: '打开工程', exact: true }).click();
  await page.getByRole('button', { name: '打开示例工程', exact: true }).click();
  await page.getByRole('button', { name: '声音模块', exact: true }).click();
  await page.getByRole('button', { name: '播放试听', exact: true }).click();
  await page.waitForFunction(() => { const audio = document.querySelector('audio'); return audio && !audio.paused && audio.currentTime > .05; });
  assert(await page.locator('audio').evaluate(audio => audio.duration > .9 && audio.duration < 1.1), '声音按钮真实播放1秒PCM音频');
  await page.getByRole('button', { name: '停止试听', exact: true }).click();
  assert(await page.locator('audio').evaluate(audio => audio.paused && audio.currentTime === 0), '停止试听清零实际播放进度');
  await page.getByRole('checkbox', { name: '3D 声音', exact: true }).check();
  await page.getByRole('button', { name: '空间', exact: true }).click();
  assert(await page.getByRole('spinbutton', { name: '最小距离', exact: true }).isVisible(), '3D声音展开空间参数');
  await page.getByRole('button', { name: '资源模块', exact: true }).click();
  await page.locator('.rw-workspace input[type=file][multiple]').setInputFiles('output/playwright/prototype-check.txt');
  await page.getByRole('heading', { name: 'prototype-check.txt', exact: true }).waitFor();
  await page.getByRole('textbox', { name: '资源包内路径', exact: true }).fill('Data/prototype-check.txt');
  await page.getByRole('button', { name: '应用路径', exact: true }).click();
  await page.getByRole('button', { name: '保存工程', exact: true }).click();
  const imported = await page.evaluate(() => JSON.parse(localStorage.getItem('forge-workbench-r02')).assets.find(a => a.name === 'prototype-check.txt'));
  assert(imported.path.replaceAll('\\', '/') === 'Data/prototype-check.txt' && imported.dataUrl.startsWith('data:'), '导入真实文件并保存包内路径和内容');
  await page.getByRole('button', { name: '战役模块', exact: true }).click();
  await page.getByRole('textbox', { name: '关卡标题', exact: true }).fill('北境哨站 · 修订');
  await page.getByRole('textbox', { name: '关卡标题', exact: true }).press('Tab');
  assert(await page.getByRole('cell', { name: '北境哨站 · 修订', exact: true }).isVisible(), '战役章节属性即时同步到章节表');
  await page.getByRole('button', { name: 'AI模块', exact: true }).click();
  await page.getByRole('spinbutton', { name: '目标总量 1', exact: true }).fill('7');
  await page.getByRole('spinbutton', { name: '目标总量 1', exact: true }).press('Tab');
  await page.getByRole('button', { name: '保存工程', exact: true }).click();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('forge-workbench-r02')));
  assert(saved.ai.build[0].count === 7 && saved.campaign.chapters[0].subtitle.endsWith('修订') && saved.sounds[0].spatial, 'AI、战役和声音修改共存于同一工程');
  await page.reload();
  await page.getByRole('button', { name: 'AI模块', exact: true }).click();
  assert(await page.getByRole('spinbutton', { name: '目标总量 1', exact: true }).inputValue() === '7', '刷新后恢复R02工程而非重建样例');
  await page.getByRole('button', { name: '触发器模块', exact: true }).click();
  await page.getByRole('button', { name: '间隔 / 秒 30', exact: true }).click();
  return { passed: checks.length, checks, parameterSnapshot: await page.locator('.tw-dialog').ariaSnapshot() };
}
