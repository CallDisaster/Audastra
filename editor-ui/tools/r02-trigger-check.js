async (page) => {
  const checks = [];
  const assert = (ok, text) => { if (!ok) throw new Error(text); checks.push(text); };
  await page.getByRole('spinbutton', { name: '间隔 / 秒', exact: true }).fill('45');
  await page.getByRole('button', { name: '应用', exact: true }).click();
  assert(await page.getByRole('button', { name: '间隔 / 秒 45', exact: true }).isVisible(), '节点参数弹层提交回蓝图');
  await page.getByRole('button', { name: '传统', exact: true }).click();
  assert(await page.getByRole('button', { name: /45/ }).count() > 0, '传统触发树显示同一参数值');
  await page.screenshot({ path: 'output/playwright/workbench-r02-traditional.png' });
  await page.getByRole('button', { name: '代码', exact: true }).click();
  assert((await page.getByRole('textbox', { name: '触发器代码', exact: true }).inputValue()).includes('45'), '代码预览使用更新后的事件参数');
  for (const language of ['vJass', 'Lua', 'JASS']) {
    await page.getByRole('combobox', { name: '代码语言', exact: true }).selectOption(language);
    const code = await page.getByRole('textbox', { name: '触发器代码', exact: true }).inputValue();
    assert(code.length > 200 && (language === 'Lua' ? !code.includes('endfunction') : code.includes('endfunction')), `${language}生成预览可切换`);
  }
  await page.getByRole('button', { name: '转为自定义文本', exact: true }).click();
  const source = await page.getByRole('textbox', { name: '触发器代码', exact: true }).inputValue();
  await page.getByRole('textbox', { name: '触发器代码', exact: true }).fill(source + '\n// R02 preserved custom edit');
  await page.getByRole('button', { name: '回转预览', exact: true }).click();
  assert(await page.getByText('恢复转换前结构，不反编译修改代码', { exact: true }).isVisible(), '修改文本回转明确说明恢复的是原结构');
  await page.getByRole('button', { name: '保留脚本并恢复原结构', exact: true }).click();
  await page.getByRole('button', { name: '蓝图', exact: true }).click();
  const event = page.locator('.tw-node').filter({ hasText: '定时事件' });
  const branch = page.locator('.tw-node').filter({ hasText: '条件分支' });
  await event.click({ position: { x: 40, y: 20 } });
  await branch.click({ position: { x: 40, y: 20 }, modifiers: ['Shift'] });
  assert(await page.locator('.tw-node.selected').count() === 2, 'Shift 多选两个节点');
  const before = await event.boundingBox();
  await page.mouse.move(before.x + 40, before.y + 20); await page.mouse.down();
  await page.mouse.move(before.x + 80, before.y + 40, { steps: 8 }); await page.mouse.up();
  await page.getByRole('button', { name: '保存工程', exact: true }).click();
  const p = await page.evaluate(() => JSON.parse(localStorage.getItem('forge-workbench-r02')));
  assert(p.graphs[0].nodes[0].x > 50 && p.graphs[0].nodes[1].x > 360, '拖动多选组同时更新两个节点坐标');
  assert(p.scripts.some(s => s.content.includes('R02 preserved custom edit')), '修改后的自定义文本完整保留为脚本');
  await page.locator('.tw-canvas').focus();
  await page.locator('.tw-canvas').press('Control+c');
  await page.locator('.tw-canvas').press('Control+v');
  assert(await page.locator('.tw-node').count() === 8, '多选复制粘贴增加两个节点');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  assert(await page.locator('.tw-node').count() === 6, '撤销批量粘贴还原节点数');
  const canvas = await page.locator('.tw-canvas').boundingBox();
  await page.mouse.click(canvas.x + 45, canvas.y + canvas.height - 90, { button: 'right' });
  await page.getByRole('textbox', { name: '搜索函数', exact: true }).fill('输出消息');
  await page.getByRole('textbox', { name: '搜索函数', exact: true }).press('Enter');
  assert(await page.locator('.tw-node').count() === 7, '画布右键搜索并创建函数节点');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await page.getByRole('button', { name: '变量模块', exact: true }).click();
  return { passed: checks.length, checks, variablesSnapshot: (await page.locator('.wb-workspace-slot').ariaSnapshot()).slice(0, 5000) };
}
