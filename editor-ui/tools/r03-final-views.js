async (page) => {
  const errors=[];
  const onError=error=>errors.push(error.message);
  const onConsole=message=>{if(['error','warning'].includes(message.type()))errors.push(message.text());};
  page.on('pageerror',onError);page.on('console',onConsole);
  await page.setViewportSize({width:1600,height:1000});
  await page.getByRole('button',{name:'打开工程',exact:true}).click();
  await page.getByRole('button',{name:'打开示例工程',exact:true}).click();
  await page.getByRole('button',{name:'触发器模块',exact:true}).click();
  const interval=page.locator('.tw-node[data-definition="core.interval"]').getByRole('textbox',{name:'间隔 / 秒',exact:true});
  await interval.fill('66');await interval.press('Control+s');
  await page.locator('.wb-toast').filter({hasText:'已保存'}).waitFor({state:'visible'});
  await page.reload({waitUntil:'domcontentloaded'});
  if(await interval.inputValue()!=='66')throw new Error('行内输入 Ctrl+S 未保存');
  await interval.fill('30');await interval.press('Enter');
  await page.getByRole('button',{name:'适应画布 · F',exact:true}).click();
  const node=page.locator('.tw-node[data-definition="core.spawn"]');
  await node.getByRole('button',{name:'选择对象模板',exact:true}).click();
  const picker=page.getByRole('dialog',{name:'对象模板选择器',exact:true});
  await picker.getByRole('button',{name:'选择守卫步兵 h001',exact:true}).hover();
  await picker.getByRole('tooltip',{name:'守卫步兵详细信息',exact:true}).waitFor({state:'visible'});
  await picker.evaluate(async el=>{await Promise.all(el.getAnimations({subtree:true}).map(a=>a.finished.catch(()=>{})));});
  const box=await picker.boundingBox(), anchor=await node.boundingBox();
  if(box.x<anchor.x+anchor.width)throw new Error('有足够空间时应保持节点右侧');
  const portraits=await picker.locator('.object-portrait').evaluateAll(elements=>elements.map(el=>{const r=el.getBoundingClientRect();return {width:r.width,height:r.height};}));
  if(portraits.some(r=>Math.abs(r.width-r.height)>1))throw new Error('头像必须保持方形');
  await page.locator('.wb-toast').waitFor({state:'hidden'});
  await page.screenshot({path:'output/playwright/workbench-r03-blueprint-selector.png'});
  await page.getByRole('button',{name:'物体模块',exact:true}).click();
  await page.locator('.ow-object-list').getByRole('button',{name:/白银领主/}).click();
  await page.getByRole('button',{name:'编辑技能列表',exact:true}).click();
  const objects=page.getByRole('dialog',{name:'技能列表编辑器',exact:true});
  await objects.getByRole('button',{name:'选择奥术冲击 A001',exact:true}).hover();
  await objects.getByRole('tooltip',{name:'奥术冲击详细信息',exact:true}).waitFor({state:'visible'});
  await objects.evaluate(async el=>{await Promise.all(el.getAnimations({subtree:true}).map(a=>a.finished.catch(()=>{})));});
  await page.screenshot({path:'output/playwright/workbench-r03-object-selector.png'});
  await objects.getByRole('button',{name:'完成',exact:true}).click();
  await page.getByRole('button',{name:'触发器模块',exact:true}).click();
  await page.getByRole('button',{name:'保存工程',exact:true}).click();
  page.off('pageerror',onError);page.off('console',onConsole);
  if(errors.length)throw new Error(errors.join('\n'));
  return {rightPicker:box,anchor,portraits,consoleErrors:errors,shots:['workbench-r03-blueprint-selector.png','workbench-r03-object-selector.png']};
}
